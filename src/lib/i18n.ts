export function translate(lang: Lang, key: DictKey, vars?: Record<string, string | number>) {
  let s = (DICTS[lang] ?? en)[key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}
